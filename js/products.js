/**
 * Finds a single product by its numeric ID
 */
function getProductById(id) {
  const numericId = parseInt(id, 10);
  return products.find(p => p.id === numericId) || null;
}

/**
 * Formats a number to Pakistani Rupee currency string
 * Example: 5500 -> "Rs. 5,500"
 */
function formatPKR(amount) {
  if (typeof amount !== 'number') {
    amount = parseFloat(amount) || 0;
  }
  return "Rs. " + amount.toLocaleString('en-PK');
}

/**
 * Renders star icons based on rating out of 5
 */
function renderStars(rating) {
  const fullStars = Math.floor(rating);
  const hasHalfStar = rating % 1 >= 0.5;
  let starsHtml = '';

  for (let i = 0; i < fullStars; i++) {
    starsHtml += '<span class="star star-full" aria-hidden="true">&#9733;</span>';
  }
  if (hasHalfStar) {
    starsHtml += '<span class="star star-half" aria-hidden="true">&#9733;</span>';
  }
  const remaining = 5 - fullStars - (hasHalfStar ? 1 : 0);
  for (let i = 0; i < remaining; i++) {
    starsHtml += '<span class="star star-empty" aria-hidden="true">&#9734;</span>';
  }

  return `<span class="stars" title="${rating} out of 5 stars">${starsHtml} <span class="rating-number">(${rating})</span></span>`;
}

/**
 * Returns HTML badge element if badge exists
 */
function getBadgeHTML(badge) {
  if (!badge) return '';
  const badgeClass = badge.toLowerCase().replace(/\s+/g, '-');
  return `<span class="product-badge badge-${badgeClass}">${badge}</span>`;
}

/**
 * Fallback image handler for all images
 */
function handleImageError(img, id) {
  img.onerror = null;
  img.src = `https://picsum.photos/seed/tme-${id || 'product'}/600/750`;
}
